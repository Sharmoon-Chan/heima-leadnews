# P1.0 synthetic dataset generator (ASCII only: Windows PowerShell 5.1 reads BOM-less
# .ps1 as ANSI/GBK, which would corrupt non-ASCII literals).
#
# Target: an ISOLATED test schema built from the REAL course DDL
# (see p1-schema-leadnews_article_p1.sql, dumped from the Windows MySQL 8.0.34 course DB).
# The course DB itself is never written to.
#
# Contract:
#   - article ids start at 9007199254741000, i.e. every id is > 2^53-1 (JS safe integer limit),
#     so id precision problems are visible instead of theoretical.
#   - ids are dense: BaseId .. BaseId+Count-1
#   - missing ids (never inserted) are in a disjoint range
#   - fixed title prefix / body / static_url=NULL for every row so responses are comparable
#   - LCG with a fixed seed: same args produce a byte-identical SQL file
#
# Usage:
#   powershell -NoProfile -ExecutionPolicy Bypass -File benchmarks/data/generate-p1-data.ps1 `
#     -OutDir D:/Code/Java/heima-leadnews/_optimization-artifacts/20261029-P1.0/data
param(
    [Parameter(Mandatory = $true)][string]$OutDir,
    [int]$Count = 10000,
    [long]$BaseId = 9007199254741000,
    [long]$MissingBaseId = 9007199254760000,
    [int]$MissingCount = 100,
    [long]$Seed = 20261029,
    [int]$BatchSize = 200
)

$ErrorActionPreference = 'Stop'
$inv = [System.Globalization.CultureInfo]::InvariantCulture
New-Item -ItemType Directory -Force -Path $OutDir | Out-Null

$sqlPath = Join-Path $OutDir 'p1-data.sql'
$hotPath = Join-Path $OutDir 'ids-hot.txt'
$missPath = Join-Path $OutDir 'ids-missing.txt'

$state = [int64]$Seed
function Next-Rand([int]$max) {
    # 32-bit LCG (glibc constants) kept in int64 to avoid uint64 overflow in PS 5.1
    $script:state = (($script:state * 1103515245) + 12345) -band 0x7FFFFFFF
    return [int]($script:state % $max)
}

$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine('-- P1.0 synthetic dataset, generated by benchmarks/data/generate-p1-data.ps1')
[void]$sb.AppendLine("-- Count=$Count BaseId=$BaseId Seed=$Seed (all ids > 2^53-1)")
[void]$sb.AppendLine('SET NAMES utf8mb4;')
[void]$sb.AppendLine('SET autocommit=0;')
[void]$sb.AppendLine('TRUNCATE TABLE `ap_article_content`;')
[void]$sb.AppendLine('TRUNCATE TABLE `ap_article_config`;')
[void]$sb.AppendLine('TRUNCATE TABLE `ap_article`;')

$baseTime = [datetime]::ParseExact('2026-10-29 00:00:00', 'yyyy-MM-dd HH:mm:ss', $inv)
# fixed body: 12 repeats of a 74-char sentence => ~900 chars, same for every article
$body = '<p>' + ('P1 synthetic article body used for the cache A/B control experiment. ' * 12) + '</p>'

for ($offset = 0; $offset -lt $Count; $offset += $BatchSize) {
    $end = [Math]::Min($offset + $BatchSize, $Count)
    $rows = [System.Collections.Generic.List[string]]::new()
    for ($i = $offset; $i -lt $end; $i++) {
        $id = $BaseId + $i
        $authorId = 1000 + ($i % 50)
        $channelId = 1 + ($i % 10)
        $layout = $i % 3
        $flag = $i % 5
        $likes = Next-Rand 5000
        $collection = Next-Rand 2000
        $comment = Next-Rand 1000
        $views = 10000 + (Next-Rand 90000)
        $pub = $baseTime.AddSeconds(-($i * 180))
        $pubStr = $pub.ToString('yyyy-MM-dd HH:mm:ss', $inv)
        # NOTE: channel_name is varchar(10) in the real DDL, keep it short (strict mode would reject longer)
        $title = "P1 article $i"
        $rows.Add("($id,'$title',$authorId,'p1a',$channelId,'ch$channelId',$layout,$flag,NULL,'p1',$likes,$collection,$comment,$views,1,1,1,'$pubStr','$pubStr',1,1,NULL)")
    }
    [void]$sb.AppendLine('INSERT INTO `ap_article` (`id`,`title`,`author_id`,`author_name`,`channel_id`,`channel_name`,`layout`,`flag`,`images`,`labels`,`likes`,`collection`,`comment`,`views`,`province_id`,`city_id`,`county_id`,`created_time`,`publish_time`,`sync_status`,`origin`,`static_url`) VALUES')
    [void]$sb.AppendLine(($rows -join ',') + ';')
}

for ($offset = 0; $offset -lt $Count; $offset += $BatchSize) {
    $end = [Math]::Min($offset + $BatchSize, $Count)
    $rows = [System.Collections.Generic.List[string]]::new()
    for ($i = $offset; $i -lt $end; $i++) {
        $id = $BaseId + $i
        $rows.Add("($id,$id,'$body')")
    }
    [void]$sb.AppendLine('INSERT INTO `ap_article_content` (`id`,`article_id`,`content`) VALUES')
    [void]$sb.AppendLine(($rows -join ',') + ';')
}

for ($offset = 0; $offset -lt $Count; $offset += $BatchSize) {
    $end = [Math]::Min($offset + $BatchSize, $Count)
    $rows = [System.Collections.Generic.List[string]]::new()
    for ($i = $offset; $i -lt $end; $i++) {
        $id = $BaseId + $i
        $rows.Add("($id,$id,1,1,0,0)")
    }
    [void]$sb.AppendLine('INSERT INTO `ap_article_config` (`id`,`article_id`,`is_comment`,`is_forward`,`is_down`,`is_delete`) VALUES')
    [void]$sb.AppendLine(($rows -join ',') + ';')
}

[void]$sb.AppendLine('COMMIT;')
[System.IO.File]::WriteAllText($sqlPath, $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))

# hot-read set: 1000 ids, stride 7 (coprime with 10000) spread over the whole range
$hot = 1..1000 | ForEach-Object { $BaseId + (($_ * 7) % $Count) }
Set-Content -Path $hotPath -Value $hot -Encoding ASCII
$miss = 0..($MissingCount - 1) | ForEach-Object { $MissingBaseId + $_ }
Set-Content -Path $missPath -Value $miss -Encoding ASCII

$info = [ordered]@{
    generated_at_utc = [DateTime]::UtcNow.ToString('yyyy-MM-ddTHH:mm:ssZ', $inv)
    generator        = 'benchmarks/data/generate-p1-data.ps1'
    target_schema    = 'leadnews_article_p1 (isolated, built from real course DDL)'
    article_count    = $Count
    base_id          = $BaseId
    id_range         = "$BaseId..$($BaseId + $Count - 1)"
    id_above_2p53    = ($BaseId -gt 9007199254740992)
    missing_id_range = "$MissingBaseId..$($MissingBaseId + $MissingCount - 1)"
    seed             = $Seed
    body_chars       = $body.Length
    static_url       = 'NULL for every row (async static page is not exercised in P1.0)'
    p1_data_sql      = @{ path = $sqlPath; bytes = (Get-Item $sqlPath).Length; sha256 = (Get-FileHash -Algorithm SHA256 -LiteralPath $sqlPath).Hash.ToLower() }
    ids_hot_txt      = @{ path = $hotPath; lines = $hot.Count; sha256 = (Get-FileHash -Algorithm SHA256 -LiteralPath $hotPath).Hash.ToLower() }
    ids_missing_txt  = @{ path = $missPath; lines = $miss.Count; sha256 = (Get-FileHash -Algorithm SHA256 -LiteralPath $missPath).Hash.ToLower() }
}
$info | ConvertTo-Json -Depth 5 | Set-Content -Encoding UTF8 (Join-Path $OutDir 'data-manifest.json')
$info | ConvertTo-Json -Depth 5
