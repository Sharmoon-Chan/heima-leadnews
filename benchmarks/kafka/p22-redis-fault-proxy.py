"""Bounded Redis fault injection for P2.2 exact-key namespace, default transparent.
GET/SET failures and holding SET before forwarding prove the success-marker boundary.
No Redis writes are generated by this proxy itself.
"""
import socket,socketserver,sys,json,time,threading
from pathlib import Path
from datetime import datetime,timezone
ROOT=Path(sys.argv[1]).resolve()
CONTROL=ROOT/'config/redis-faults.json'
LOG=ROOT/'logs/redis-fault-proxy.jsonl'
LOCK=threading.Lock()
def log(x):
 x['utc']=datetime.now(timezone.utc).isoformat()
 with LOCK:
  with LOG.open('a',encoding='utf-8') as f:f.write(json.dumps(x)+'\n')
def frame(f):
 first=f.read(1)
 if not first:raise EOFError()
 line=f.readline()
 if not line.endswith(b'\r\n'):raise EOFError()
 raw=first+line;v=line[:-2]
 if first==b'*':
  n=int(v);args=[]
  for _ in range(max(n,0)):
   b,a=frame(f);raw+=b;args.append(a)
  return raw,args if n>=0 else None
 if first==b'$':
  n=int(v)
  if n<0:return raw,None
  b=f.read(n+2)
  if len(b)!=n+2:raise EOFError()
  return raw+b,b[:-2]
 return raw,v
class Handler(socketserver.StreamRequestHandler):
 def handle(self):
  upstream=socket.create_connection(('127.0.0.1',6379),timeout=3);uf=upstream.makefile('rb')
  try:
   while True:
    raw,args=frame(self.rfile)
    if not isinstance(args,list) or not args:raise ValueError('RESP command array required')
    command=args[0].decode('ascii',errors='replace').upper()
    is_write=command in ('SET','SETEX','PSETEX')
    key=args[1].decode('utf-8',errors='replace') if len(args)>1 and isinstance(args[1],bytes) else ''
    owned=key.startswith('p22:')
    rule=json.loads(CONTROL.read_text(encoding='utf-8')) if CONTROL.exists() else {}
    match=owned and (not rule.get('event') or rule['event'] in key)
    if match and ((command=='GET' and rule.get('fail_get')) or (is_write and rule.get('fail_set'))):
     log({'cmd':command,'key':key,'result':'injected_error'})
     self.wfile.write(b'-ERR P2.2 controlled Redis failure\r\n');self.wfile.flush();continue
    if match and is_write and rule.get('hold_set'):
     log({'cmd':command,'key':key,'result':'holding_before_set'})
     deadline=time.time()+30
     while time.time()<deadline:
      current=json.loads(CONTROL.read_text(encoding='utf-8'))
      if not current.get('hold_set'):break
      time.sleep(.1)
     # Do not send the marker after the caller crashed/timed out: this fault drops the pending operation.
     log({'cmd':command,'key':key,'result':'held_set_dropped'})
     try:self.wfile.write(b'-ERR P2.2 withheld marker write\r\n');self.wfile.flush()
     except OSError:pass
     continue
    started=time.monotonic();upstream.sendall(raw);reply,value=frame(uf)
    if owned and (command=='GET' or is_write):
     log({'cmd':command,'key':key,'result':'forwarded','reply_null':value is None,'elapsed_us':round((time.monotonic()-started)*1000000)})
    self.wfile.write(reply);self.wfile.flush()
  except (EOFError,OSError,ValueError):pass
  finally:uf.close();upstream.close()
class Server(socketserver.ThreadingTCPServer):
 allow_reuse_address=True
 daemon_threads=True
server=Server(('127.0.0.1',16385),Handler)
log({'result':'proxy_started','port':16385})
server.serve_forever()
